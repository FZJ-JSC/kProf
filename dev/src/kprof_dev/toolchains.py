"""Internal Rocky Linux 10 / Spack toolchain provisioning implementation.

The public interface is ``kprof-dev compiler``. The stdlib-only bootstrap
entry point is used internally inside the pristine Rocky Linux container.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import re
import shlex
import signal
import subprocess
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
SETTINGS_FILE = ROOT / "dev/etc/toolchains.toml"
ENV_DIR = ROOT / "dev/compilers"
DEPS_ENV_DIR = ROOT / "dev"
DEPS_MATRIX_DIR = DEPS_ENV_DIR / ".spack-matrix"
MANIFEST = ENV_DIR / "spack.yaml"
LOCKFILE = ENV_DIR / "spack.lock"


def settings() -> dict[str, Any]:
    with SETTINGS_FILE.open("rb") as stream:
        data = tomllib.load(stream)
    target = data["platform"]["target"]
    for compiler in data["compilers"]:
        if f"target={target}" not in compiler["spec"].split():
            raise ValueError(f"{compiler['selector']} must target {target}")
    selectors = [item["selector"] for item in data["compilers"]]
    if len(set(selectors)) != len(selectors):
        raise ValueError("Duplicate compiler selectors in toolchains.toml")
    return data


def manifest_content(data: dict[str, Any]) -> str:
    target = data["platform"]["target"]
    lines = [
        # REUSE-IgnoreStart
        "# SPDX-FileCopyrightText: 2026 kprof developers",
        "# SPDX-License-Identifier: Apache-2.0",
        # REUSE-IgnoreEnd
        "# Generated by kprof-dev compiler sync from dev/etc/toolchains.toml.",
        "spack:",
        "  view: false",
        "  specs:",
    ]
    lines.extend(f"    - {item['spec']}" for item in data["compilers"])
    lines.extend(
        [
            "  concretizer:",
            "    unify: when_possible",
            "  packages:",
            "    all:",
            f"      target: [{target}]",
            "",
        ]
    )
    return "\n".join(lines)


def sync(*, check: bool = False, data: dict[str, Any] | None = None) -> None:
    content = manifest_content(data or settings())
    current = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
    if check and current != content:
        raise RuntimeError(f"{MANIFEST} is out of sync; run 'kprof-dev compiler sync'")
    if not check and current != content:
        MANIFEST.write_text(content, encoding="utf-8")
        print(f"Updated {MANIFEST.relative_to(ROOT)}")


def system_compiler_for(data: dict[str, Any], selector: str) -> dict[str, Any]:
    for compiler in data["system_compilers"]:
        if compiler["selector"].lower() == selector.lower():
            return compiler
    valid = ", ".join(item["selector"] for item in data["system_compilers"])
    raise ValueError(f"Unknown system compiler {selector!r}; choose from {valid}")


def compiler_for(data: dict[str, Any], selector: str) -> dict[str, str]:
    for compiler in data["compilers"]:
        if compiler["selector"].lower() == selector.lower():
            return compiler
    valid = ", ".join(item["selector"] for item in data["compilers"])
    raise ValueError(f"Unknown compiler {selector!r}; choose from {valid}")


def verify_platform(data: dict[str, Any]) -> None:
    if platform.machine().lower() not in ("x86_64", "amd64"):
        raise RuntimeError("Compiler cache requires an x86-64 host")
    values = {}
    for line in Path("/etc/os-release").read_text(encoding="utf-8").splitlines():
        if "=" in line:
            key, value = line.split("=", 1)
            values[key] = value.strip('"')
    if values.get("ID") != "rocky" or values.get("VERSION_ID", "").split(".")[0] != "10":
        raise RuntimeError("Compiler provisioning requires a Rocky Linux 10 container")
    # AVX2 alone isn't sufficient for x86-64-v3: check the other extensions too.
    cpuinfo = Path("/proc/cpuinfo").read_text(encoding="utf-8")
    flags = set(re.search(r"^flags\s*:\s*(.*)$", cpuinfo, re.MULTILINE).group(1).split())
    required = {"avx", "avx2", "bmi1", "bmi2", "fma", "f16c", "movbe"}
    missing = required - flags
    if "lzcnt" not in flags and "abm" not in flags:
        missing.add("lzcnt")
    if missing:
        raise RuntimeError("CPU does not satisfy x86-64-v3: " + ", ".join(sorted(missing)))


def run_command(*args: str) -> None:
    print("+", shlex.join(args), flush=True)
    subprocess.run(args, check=True)


def _checkout_tag(directory: Path, repository: str, ref: str) -> None:
    """Keep pinned Spack sources in the persistent /opt/spack Docker volume."""
    if not (directory / ".git").is_dir():
        if directory.exists():
            raise RuntimeError(f"Existing checkout is not a Git repository: {directory}")
        run_command("git", "clone", "--depth", "1", "--branch", ref, repository, str(directory))
        return
    result = subprocess.run(
        ["git", "-C", str(directory), "rev-parse", "-q", "--verify", f"{ref}^{{commit}}"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False,
    )
    if result.returncode:
        run_command("git", "-C", str(directory), "fetch", "--depth", "1", "origin", f"refs/tags/{ref}:refs/tags/{ref}")
    run_command("git", "-C", str(directory), "checkout", "--force", "--detach", ref)


def bootstrap_spack(data: dict[str, Any]) -> None:
    """Prepare the identical Rocky/Spack toolchain on desktop and in CI."""
    bootstrap = data["bootstrap"]
    compiler = system_compiler_for(data, bootstrap["system_compiler"])
    # The prebuilt image contains these RPMs and pinned Spack sources. Bare
    # Rocky remains a supported fallback until the GHCR image is published.
    packages = list(dict.fromkeys((*bootstrap["packages"], *compiler["packages"])))
    prebuilt = Path("/opt/kprof/.bootstrap-ready").exists()
    if not prebuilt:
        run_command("dnf", "install", "-y", *packages)

    store = Path(data["spack"]["install_tree"])
    if store != Path("/opt/spack"):
        raise ValueError("Compiler provisioning requires /opt/spack as its store")
    # Legacy bare-Rocky desktops keep downloaded sources in the persistent
    # /opt/spack volume. Image builds bake them into /opt/kprof instead, so
    # mounting the Spack store does not hide the image's pinned repositories.
    if prebuilt or os.environ.get("KPROF_BUILD_BOOTSTRAP_IMAGE") == "1":
        root = Path(data["spack"].get("image_source_root", "/opt/kprof"))
    else:
        root = store
    spack_src = root / "spack-src"
    if prebuilt:
        for path in (spack_src / ".git", root / "spack-packages/.git"):
            if not path.is_dir():
                raise RuntimeError(f"Incomplete prebuilt bootstrap image: missing {path}")
    else:
        _checkout_tag(spack_src, "https://github.com/spack/spack.git", data["spack"]["version"])
        _checkout_tag(
            root / "spack-packages", "https://github.com/spack/spack-packages.git",
            data["spack"]["packages_version"],
        )
    if prebuilt:
        for repo, ref in ((spack_src, data["spack"]["version"]),
                          (root / "spack-packages", data["spack"]["packages_version"])):
            expected = subprocess.run(
                ["git", "-C", str(repo), "rev-parse", f"{ref}^{{commit}}"],
                capture_output=True, text=True, check=True,
            ).stdout.strip()
            actual = subprocess.run(
                ["git", "-C", str(repo), "rev-parse", "HEAD"],
                capture_output=True, text=True, check=True,
            ).stdout.strip()
            if expected != actual:
                raise RuntimeError(f"Bootstrap image uses a different {repo.name} revision: {actual}")
    os.environ["SPACK_ROOT"] = str(spack_src)
    os.environ["PATH"] = f"{spack_src / 'bin'}:{os.environ['PATH']}"
    # CI has a new process for each step: propagate the same Spack executable
    # and root to subsequent steps without depending on setup-spack's wrapper.
    if github_path := os.environ.get("GITHUB_PATH"):
        with Path(github_path).open("a", encoding="utf-8") as stream:
            stream.write(f"{spack_src / 'bin'}\n")
    if github_env := os.environ.get("GITHUB_ENV"):
        with Path(github_env).open("a", encoding="utf-8") as stream:
            stream.write(f"SPACK_ROOT={spack_src}\n")

    namespaces = subprocess.run(
        ["spack", "repo", "list", "--namespaces"],
        check=True, capture_output=True, text=True,
    ).stdout.splitlines()
    if "builtin" not in (entry.strip() for entry in namespaces):
        run_command(
            "spack", "repo", "add", "--scope", "spack",
            str(root / "spack-packages/repos/spack_repo/builtin"),
        )

    # GCC 14 is preferred to bootstrap the compiler roots. Do not *require*
    # it globally: each development environment must be allowed to *require*
    # its own selected compiler for every language.
    run_command("spack", "config", "--scope", "spack", "add",
                f"config:install_tree:root:{root}")
    run_command("spack", "compiler", "find", "--scope", "spack", "/usr/bin")
    gcc_version = subprocess.run(
        ["/usr/bin/gcc", "-dumpfullversion", "-dumpversion"],
        check=True, capture_output=True, text=True,
    ).stdout.strip()
    expected = compiler["expected_major"]
    if not gcc_version or gcc_version.split(".")[0] != expected:
        raise RuntimeError(f"Expected bootstrap GCC {expected}, got {gcc_version!r}")
    for language in ("c", "cxx", "fortran"):
        # Earlier versions of this bootstrap wrote hard gcc@14 requirements
        # into the persistent volume. Drop those stale requirements so that
        # per-compiler environment requirements cannot conflict with them.
        # Removing an absent entry is harmless for a fresh Spack checkout.
        for key in ("require", "prefer"):
            subprocess.run(
                ["spack", "config", "--scope", "spack", "remove", f"packages:{language}:{key}"],
                check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
        run_command("spack", "config", "--scope", "spack", "add",
                    f"packages:{language}:prefer::[gcc@{gcc_version}]")
    print(f"Spack dependency compiler: GCC {gcc_version} (/usr/bin/gcc)")


def install_system_compiler(data: dict[str, Any], selector: str) -> None:
    """Install a Rocky RPM or NVIDIA HPC SDK compiler for a CI matrix entry."""
    compiler = system_compiler_for(data, selector)
    executable = Path(compiler["cxx"])
    # Bootstrap already installed Rocky GCC 14. Do not resolve the same DNF
    # transaction again simply to export its compiler paths for the matrix.
    if compiler["selector"].lower() != "gcc:14" or not executable.is_file():
        if url := compiler.get("repo_url"):
            repo_path = Path("/etc/yum.repos.d/nvhpc.repo")
            run_command("curl", "-fsSL", url, "-o", str(repo_path))
        run_command("dnf", "install", "-y", *compiler["packages"])
    if not executable.is_file() or not os.access(executable, os.X_OK):
        raise RuntimeError(f"System compiler was not installed: {executable}")
    major = compiler.get("expected_major")
    if compiler["selector"].startswith("GCC:"):
        result = subprocess.run(
            [str(executable), "-dumpfullversion", "-dumpversion"],
            capture_output=True, text=True, check=True,
        )
        if result.stdout.strip().split(".")[0] != major:
            raise RuntimeError(f"Expected GCC {major}, got {result.stdout.strip()}")
    elif compiler["selector"].startswith("Clang:"):
        result = subprocess.run(
            [str(executable), "--version"], capture_output=True, text=True, check=True,
        )
        if not re.search(rf"\bversion {re.escape(major)}\.", result.stdout):
            raise RuntimeError(f"Expected Clang {major} at {executable}")
    if env_file := os.environ.get("GITHUB_ENV"):
        with Path(env_file).open("a", encoding="utf-8") as stream:
            stream.write(f"KPROF_CXX={executable}\n")
            c_compiler = {"g++": "gcc", "nvc++": "nvc", "clang++": "clang"}.get(executable.name)
            if c_compiler:
                stream.write(f"KPROF_CC={executable.with_name(c_compiler)}\n")
            if toolset_env := compiler.get("toolset_env"):
                stream.write(f"KPROF_TOOLSET_ENV={toolset_env}\n")
    run_command(str(executable), "--version")


def restore_workspace_ownership() -> None:
    """Return bind-mounted Spack metadata to the desktop user, even on errors."""
    uid, gid = os.environ.get("KPROF_HOST_UID"), os.environ.get("KPROF_HOST_GID")
    worktree = Path("/workspace/dev/compilers")
    if uid is None or gid is None or not worktree.is_dir():
        return
    # -hR does not dereference links. Never recurse into /opt/spack (the volume).
    # The development environment is also generated in the bind-mounted tree.
    paths = [worktree, Path("/workspace/dev/.spack-matrix"), Path("/workspace/dev/.spack-env")]
    for path in paths:
        if path.exists():
            run_command("chown", "-hR", f"{int(uid)}:{int(gid)}", str(path))
            run_command("chmod", "-R", "u+rwX", str(path))


def ensure_lock() -> None:
    if not LOCKFILE.is_file():
        raise RuntimeError(
            "Missing dev/compilers/spack.lock: build and publish the compiler "
            "environment, then commit its lockfile before restoring"
        )


def dependency_compiler(data: dict[str, Any], selector: str) -> tuple[str, Path]:
    """Return exact Spack compiler provider and the selected C++ binary."""
    if selector.lower() == "gcc:14" or selector.lower().startswith("nvhpc:"):
        compiler = system_compiler_for(data, selector)
        version = compiler.get("expected_major") or selector.split(":", 1)[1]
        # The actual system GCC version is found during bootstrap. Avoid a
        # floating gcc@14 constraint that could choose a different compiler.
        if selector.lower() == "gcc:14":
            result = subprocess.run(
                ["/usr/bin/gcc", "-dumpfullversion", "-dumpversion"],
                check=True, capture_output=True, text=True,
            )
            version = result.stdout.strip()
        return f"{'nvhpc' if selector.lower().startswith('nvhpc:') else 'gcc'}@={version}", Path(compiler["cxx"])

    compiler = compiler_for(data, selector)
    spec = compiler["spec"]
    match = re.match(r"^(gcc|llvm)@([^ +~]+)", spec)
    if match is None:
        raise ValueError(f"Unrecognized compiler root spec: {spec}")
    result = subprocess.run(
        ["spack", "-e", str(ENV_DIR), "location", "-i", spec],
        check=True, capture_output=True, text=True,
    )
    return f"{match.group(1)}@={match.group(2)}", Path(result.stdout.strip()) / compiler["cxx"]


def deps_environment(selector: str) -> Path:
    """Each matrix member has its own Spack manifest and concrete lockfile."""
    if not re.fullmatch(r"[A-Za-z][A-Za-z0-9]*:[0-9]+(?:\.[0-9]+)*", selector):
        raise ValueError(f"Invalid compiler selector {selector!r}")
    return DEPS_MATRIX_DIR / selector.lower().replace(":", "-").replace(".", "-")


def prepare_deps_environment(selector: str, compiler_spec: str) -> Path:
    """Generate one stable manifest/lockfile per compiler configuration.

    Re-concretizing an unchanged manifest can silently change package hashes,
    making the cache and the build being tested non-reproducible. Only invalidate
    the lock if its inputs have actually changed.
    """
    directory = deps_environment(selector)
    directory.mkdir(parents=True, exist_ok=True)
    source_text = (DEPS_ENV_DIR / "spack.yaml").read_text(encoding="utf-8")
    marker = "  packages:\n"
    if source_text.count(marker) != 1:
        raise RuntimeError("dev/spack.yaml must have exactly one Spack packages: section")
    nvhpc = selector.lower().startswith("nvhpc:")
    if nvhpc:
        # The kprof-dev bundle depends on CMake/Ninja as *executables*.
        # Compiling their dependency DAG with NVHPC is both unnecessary and
        # problematic (e.g. Ninja's GCC warning flags, zstd's dependency-file
        # flags). Build host tools with the Rocky system GCC instead. The
        # application-linked Catch2 library must still be built with NVHPC.
        host_compiler, _ = dependency_compiler(settings(), "GCC:14")
        extra = "".join(
            f"    {language}:\n      prefer: ['{host_compiler}']\n"
            for language in ("c", "cxx", "fortran")
        )
        extra += (
            "    catch2:\n"
            f"      require: ['%cxx={compiler_spec}']\n"
        )
        # Python is executed as a separate host tool by Meson/Ninja, rather
        # than linked into the C++ application. NVHPC cannot compile Python.
    else:
        extra = "".join(
            f"    {language}:\n      require: ['{compiler_spec}']\n"
            for language in ("c", "cxx", "fortran")
        )
    if nvhpc:
        version = subprocess.run(
            ["/usr/bin/python3", "-c", "import platform; print(platform.python_version())"],
            check=True, capture_output=True, text=True,
        ).stdout.strip()
        if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version):
            raise RuntimeError(f"Cannot identify system Python version: {version!r}")
        extra += (
            "    python:\n"
            "      buildable: false\n"
            "      externals:\n"
            f"      - spec: python@={version}\n"
            "        prefix: /usr\n"
        )
    rendered = source_text.replace(marker, marker + extra)
    rendered += (
        f"# compiler selector: {selector}\n"
        f"# Spack: {settings()['spack']['version']}\n"
        f"# spack-packages: {settings()['spack']['packages_version']}\n"
    )
    manifest = directory / "spack.yaml"
    if not manifest.is_file() or manifest.read_text(encoding="utf-8") != rendered:
        manifest.write_text(rendered, encoding="utf-8")
        (directory / "spack.lock").unlink(missing_ok=True)
    share = directory / "share"
    share.mkdir(exist_ok=True)
    repo = share / "spack"
    target = (DEPS_ENV_DIR / "share/spack").resolve()
    if repo.is_symlink() and repo.readlink() != target:
        repo.unlink()
    if not repo.is_symlink():
        if repo.exists():
            raise RuntimeError(f"Expected a repository symlink at {repo}")
        repo.symlink_to(target, target_is_directory=True)
    return directory


def validate_deps_lock(directory: Path, compiler_spec: str, data: dict[str, Any]) -> None:
    """Verify target, OS, and compiler virtual providers before install/push."""
    path = directory / "spack.lock"
    if not path.is_file():
        raise RuntimeError(f"Missing {path}; run deps install --compiler first")
    lock = json.loads(path.read_text(encoding="utf-8"))
    specs = lock.get("concrete_specs", {})
    if not specs or not lock.get("roots"):
        raise RuntimeError(f"Empty or invalid Spack lockfile: {path}")
    if lock.get("spack", {}).get("version") != data["spack"]["version"].removeprefix("v"):
        raise RuntimeError(f"Spack version mismatch in {path}")
    expected_target = data["platform"]["target"]
    name, version = compiler_spec.split("@=", 1)
    nvhpc = name == "nvhpc"
    host_name = host_version = None
    linked_nodes: set[str] = set()
    if nvhpc:
        host_spec, _ = dependency_compiler(data, "GCC:14")
        host_name, host_version = host_spec.split("@=", 1)
        # Only follow link edges out of the dev bundle. CMake and Ninja are
        # build/run tools and must not drag their GCC-built libraries into the
        # application's ABI-sensitive closure.
        pending = [root["hash"] for root in lock["roots"]]
        while pending:
            hash_ = pending.pop()
            if hash_ in linked_nodes:
                continue
            linked_nodes.add(hash_)
            parent = specs.get(hash_, {})
            for dep in parent.get("dependencies", []):
                if "link" in dep.get("parameters", {}).get("deptypes", []):
                    pending.append(dep["hash"])
    for hash_, node in specs.items():
        arch = node.get("arch", {})
        target = arch.get("target")
        # Spack lockfiles can represent target as a string or as {name: ...}.
        target_name = target.get("name") if isinstance(target, dict) else target
        # Externals (e.g., system glibc or compiler executables) commonly
        # identify their target as x86_64 even when every built dependency
        # targets x86_64_v3. Check the OS of all nodes and the CPU target of
        # the nodes actually built by Spack.
        if arch.get("platform_os") != "rocky10" or (not node.get("external") and target_name != expected_target):
            raise RuntimeError(f"Wrong OS/target in {path}: {arch}")
        for dep in node.get("dependencies", []):
            virtuals = dep.get("parameters", {}).get("virtuals", [])
            if not set(virtuals).intersection(("c", "cxx", "fortran")):
                continue
            provider = specs.get(dep.get("hash"), {})
            # NVHPC's narrowly scoped exception: host-side tools use the
            # system GCC, while every linked (non-external) dependency uses
            # NVHPC. For other toolchains all packages use the exact provider.
            expected_name, expected_version = name, version
            if nvhpc and hash_ not in linked_nodes:
                expected_name, expected_version = host_name, host_version
            if node.get("external"):
                continue
            if (provider.get("name"), provider.get("version")) != (expected_name, expected_version):
                raise RuntimeError(
                    f"Mixed compiler in {path}: expected {expected_name}@={expected_version} "
                    f"for {node.get('name')} ({virtuals}), "
                    f"found {provider.get('name')}@{provider.get('version')}"
                )


def native_deps(action: str, *, selector: str, cache_image: str | None = None) -> None:
    """One complete dependency DAG per exact compiler configuration.

    Compiler roots remain cache-only. Dependencies prefer binary buildcaches,
    then compile on misses, and may be published after a successful install.
    """
    data = settings()
    verify_platform(data)
    if os.environ.get("KPROF_DESKTOP_BOOTSTRAP") == "1":
        bootstrap_spack(data)
    compiler_spec, cxx = dependency_compiler(data, selector)
    if not cxx.is_file() or not os.access(cxx, os.X_OK):
        raise RuntimeError(f"Install selected compiler first: {cxx}")
    # The compiler must be registered before we ask Spack to concretize.
    run_command("spack", "compiler", "find", "--scope", "spack", str(cxx.parent))
    directory = deps_environment(selector)
    if action in ("install", "build"):
        directory = prepare_deps_environment(selector, compiler_spec)
    elif not (directory / "spack.yaml").is_file():
        raise RuntimeError(f"No dependency environment for {selector}; run deps install first")

    # Distinct images avoid simultaneous updates from parallel CI matrix jobs
    # to the same OCI image. Exact compiler/option hashes are still preserved.
    base = cache_image or os.environ.get("GHCR_IMAGE") or data["buildcache"]["image"]
    image = base + "-deps-" + directory.name
    configure_spack(data, image, name="kprof-deps-cache")
    env_arg = ("-e", str(directory))
    if action in ("install", "build"):
        if not (directory / "spack.lock").exists():
            run_command("spack", *env_arg, "concretize", "--fresh")
        validate_deps_lock(directory, compiler_spec, data)
        if action == "build":
            run_command("spack", *env_arg, "install", "--no-cache", "--only-concrete")
        else:
            run_command("spack", *env_arg, "install", "--only-concrete")
        if github_env := os.environ.get("GITHUB_ENV"):
            with Path(github_env).open("a", encoding="utf-8") as stream:
                stream.write(f"KPROF_DEPS_ENV={directory}\n")
        else:
            print(f"Spack development environment: {directory}")
    elif action in ("push", "restore"):
        validate_deps_lock(directory, compiler_spec, data)
        if action == "push":
            if not os.environ.get("GHCR_USER") or not os.environ.get("GHCR_TOKEN"):
                raise RuntimeError("GHCR_USER and GHCR_TOKEN are required for push")
            # Binary-cache installs do not materialize unused build-only deps.
            # Publish every installed node (including build tools when built),
            # without failing on absent build-only nodes in the lockfile.
            run_command("spack", *env_arg, "buildcache", "push", "--unsigned",
                        "--allow-missing", "--update-index", "kprof-deps-cache")
        else:
            run_command("spack", *env_arg, "install", "--cache-only", "--only-concrete")
    else:
        raise ValueError(f"Unknown development dependency action {action!r}")


def configure_spack(data: dict[str, Any], cache_image: str, *, name: str | None = None) -> None:
    install_tree = data["spack"]["install_tree"]
    if install_tree != "/opt/spack":
        raise ValueError("The container volume and Spack install tree must be /opt/spack")
    run_command("spack", "config", "--scope", "spack", "add", f"config:install_tree:root:{install_tree}")
    name = name or data["buildcache"]["name"]
    result = subprocess.run(["spack", "mirror", "list"], capture_output=True, text=True, check=True)
    if re.search(rf"^\s*{re.escape(name)}\s", result.stdout, re.MULTILINE):
        run_command("spack", "mirror", "remove", "--scope", "spack", name)
    opts: list[str] = []
    if os.environ.get("GHCR_USER") and os.environ.get("GHCR_TOKEN"):
        opts = ["--oci-username-variable", "GHCR_USER", "--oci-password-variable", "GHCR_TOKEN"]
    run_command(
        "spack", "mirror", "add", "--scope", "spack", "--type", "binary", "--unsigned",
        *opts, name, f"oci://{cache_image}",
    )


def compiler_closure(lock: dict[str, Any], root_specs: tuple[str, ...]) -> dict[str, dict[str, Any]]:
    """Non-external nodes reachable from the requested locked roots."""
    specs = lock.get("concrete_specs", {})
    roots = lock.get("roots", [])
    chosen = [r for r in roots if not root_specs or r.get("spec") in root_specs]
    if len(chosen) != len(root_specs) and root_specs:
        raise RuntimeError(f"Compiler lockfile does not contain all requested roots: {root_specs}")
    if not chosen:
        raise RuntimeError("Compiler lockfile has no roots")
    result: dict[str, dict[str, Any]] = {}

    def visit(hash_: str) -> None:
        if hash_ in result:
            return
        node = specs.get(hash_)
        if node is None:
            raise RuntimeError(f"Compiler lockfile references missing dependency {hash_}")
        result[hash_] = node
        for edge in node.get("dependencies", []):
            visit(edge["hash"])

    for root in chosen:
        visit(root["hash"])
    return {hash_: node for hash_, node in result.items() if not node.get("external")}


def validate_compiler_lock(data: dict[str, Any], root_specs: tuple[str, ...]) -> dict[str, dict[str, Any]]:
    """Reject incompatible/stale compiler locks before building or publishing."""
    ensure_lock()
    lock = json.loads(LOCKFILE.read_text(encoding="utf-8"))
    if lock.get("spack", {}).get("version") != data["spack"]["version"].removeprefix("v"):
        raise RuntimeError("Compiler spack.lock was generated with another Spack version")
    closure = compiler_closure(lock, root_specs)
    for hash_, node in closure.items():
        arch = node.get("arch", {})
        target = arch.get("target")
        target = target.get("name") if isinstance(target, dict) else target
        if arch.get("platform_os") != "rocky10" or target != data["platform"]["target"]:
            raise RuntimeError(f"Invalid compiler graph target for {node['name']}/{hash_}: {arch}")
    return closure


def require_installed_compiler_graph(data: dict[str, Any], root_specs: tuple[str, ...]) -> None:
    """Do not push just compiler roots while gcc-runtime or other DAG nodes are missing."""
    closure = validate_compiler_lock(data, root_specs)
    result = subprocess.run(
        ["spack", "find", "--format", "{hash}"],
        check=True, capture_output=True, text=True,
    )
    installed = {line.strip() for line in result.stdout.splitlines() if re.fullmatch(r"[a-z2-7]{32}", line.strip())}
    missing = [(node["name"], node["version"], hash_) for hash_, node in closure.items() if hash_ not in installed]
    if missing:
        description = "\n".join(f"  {name}@{version}/{hash_[:7]}" for name, version, hash_ in missing)
        raise RuntimeError(
            "Compiler cache cannot be published: the locked Spack store is incomplete.\n"
            f"Missing {len(missing)} installed packages (including build dependencies):\n{description}\n"
            "Run 'kprof-dev compiler build' with the SAME --volume, then push again."
        )


def native(action: str, *, compilers: tuple[str, ...] = (), cache_image: str | None = None) -> None:
    data = settings()
    verify_platform(data)
    if action == "bootstrap":
        bootstrap_spack(data)
        return
    if action == "system-install":
        if len(compilers) != 1:
            raise ValueError("system-install requires exactly one compiler selector")
        install_system_compiler(data, compilers[0])
        return
    if os.environ.get("KPROF_DESKTOP_BOOTSTRAP") == "1":
        bootstrap_spack(data)
    image = cache_image or os.environ.get("GHCR_IMAGE") or data["buildcache"]["image"]
    if action == "build":
        sync(data=data)
    elif action in {"push", "restore", "install"}:
        sync(check=True, data=data)
        ensure_lock()
    configure_spack(data, image)
    env_arg = ("-e", str(ENV_DIR))
    roots = tuple(compiler_for(data, selector)["spec"] for selector in compilers)
    if action == "build":
        # Deliberate re-concretization is a desktop-only operation. Any resulting
        # lockfile change MUST be committed alongside the cache it describes.
        run_command("spack", *env_arg, "concretize", "--fresh", "--force")
        validate_compiler_lock(data, roots)
        run_command("spack", *env_arg, "install", "--no-cache", "--only-concrete", *roots)
        require_installed_compiler_graph(data, roots)
        print("Compiler graph is complete. Commit dev/compilers/spack.lock after publishing.")
    elif action in ("restore", "install"):
        validate_compiler_lock(data, roots)
        if action == "install" and len(compilers) != 1:
            raise ValueError("install requires exactly one --compiler selector")
        # This explicitly forbids Spack compiling ANY part of compiler graph.
        run_command("spack", *env_arg, "install", "--cache-only", "--only-concrete", *roots)
        if action == "restore":
            run_command("spack", *env_arg, "find", "-d")
        else:
            compiler = compiler_for(data, compilers[0])
            result = subprocess.run(
                ["spack", *env_arg, "location", "-i", compiler["spec"]],
                capture_output=True, text=True, check=True,
            )
            executable = Path(result.stdout.strip()) / compiler["cxx"]
            if not executable.is_file() or not os.access(executable, os.X_OK):
                raise RuntimeError(f"Compiler executable not found: {executable}")
            run_command(str(executable), "--version")
            if path := os.environ.get("GITHUB_ENV"):
                with Path(path).open("a", encoding="utf-8") as stream:
                    stream.write(f"KPROF_CXX={executable}\n")
                    cc = executable.with_name("gcc" if executable.name == "g++" else "clang")
                    stream.write(f"KPROF_CC={cc}\n")
            else:
                print(f"CXX={executable}")
    elif action == "push":
        if not os.environ.get("GHCR_USER") or not os.environ.get("GHCR_TOKEN"):
            raise RuntimeError("GHCR_USER and GHCR_TOKEN are required for push")
        require_installed_compiler_graph(data, roots)
        run_command(
            "spack", *env_arg, "buildcache", "push", "--unsigned",
            "--with-build-dependencies", "--update-index", data["buildcache"]["name"], *roots,
        )

    elif action == "inspect":
        run_command("spack", "mirror", "list")
        run_command("spack", "compiler", "list", "--remote")
        if LOCKFILE.exists():
            run_command("spack", *env_arg, "find", "-d")
    else:
        raise ValueError(f"Unknown toolchain action: {action}")


def execute(
    action: str,
    *,
    backend: str = "docker",
    compilers: tuple[str, ...] = (),
    volume: str | None = None,
    image: str | None = None,
    cache_image: str | None = None,
) -> None:
    data = settings()
    is_deps = action.startswith("deps-")
    if is_deps and len(compilers) != 1:
        raise ValueError("Development dependency actions require exactly one --compiler selector")
    if not is_deps:
        for compiler in compilers:
            (system_compiler_for if action == "system-install" else compiler_for)(data, compiler)
    if backend == "native":
        if is_deps:
            native_deps(action.removeprefix("deps-"), selector=compilers[0], cache_image=cache_image)
        else:
            native(action, compilers=compilers, cache_image=cache_image)
        return
    if backend != "docker":
        raise ValueError(f"Unknown backend {backend!r}")
    if action == "system-install":
        raise ValueError("system-install must run with --backend native in the Rocky container")
    mount_root = data["spack"]["install_tree"]
    if mount_root != "/opt/spack":
        raise ValueError("The compiler Spack store must be mounted at /opt/spack")
    volume_name = volume or os.environ.get("KPROF_SPACK_VOLUME") or data["platform"]["volume"]
    rocky_image = image or data["platform"]["image"]
    cache = cache_image or os.environ.get("GHCR_IMAGE") or data["buildcache"]["image"]
    cmd = [
        "docker", "run", "--rm", "-i",
        "--mount", f"type=bind,source={ROOT},target=/workspace",
        "--mount", f"type=volume,source={volume_name},target={mount_root}",
        "-w", "/workspace",
        "-e", "GHCR_USER", "-e", "GHCR_TOKEN", "-e", f"GHCR_IMAGE={cache}",
        "-e", "SPACK_DISABLE_LOCAL_CONFIG=1",
        "-e", "KPROF_DESKTOP_BOOTSTRAP=1",
        "-e", f"KPROF_HOST_UID={os.getuid()}",
        "-e", f"KPROF_HOST_GID={os.getgid()}",
        rocky_image, "python3", "dev/src/kprof_dev/toolchains.py", "--backend", "native", action,
    ]
    for compiler in compilers:
        cmd.extend(("--compiler", compiler))
    run_command(*cmd)


def set_packages_version(ref: str) -> None:
    """Update the Spack package-repository pin used by desktop and CI."""
    if not re.fullmatch(r"v20[0-9]{2}\.[0-9]{2}\.[0-9]+", ref):
        raise ValueError("Expected a spack-packages release such as v2026.10.0")
    current = get("spack.packages_version")
    content = SETTINGS_FILE.read_text(encoding="utf-8")
    old = f'packages_version = "{current}"'
    if content.count(old) != 1:
        raise RuntimeError("Could not uniquely update packages_version in dev/etc/toolchains.toml")
    SETTINGS_FILE.write_text(content.replace(old, f'packages_version = "{ref}"'), encoding="utf-8")
    print("Updated dev/etc/toolchains.toml; rebuild and republish, then commit spack.lock")


def get(key: str) -> str:
    value: Any = settings()
    for segment in key.split("."):
        value = value[segment]
    if not isinstance(value, str):
        raise TypeError(f"Not a string config setting: {key}")
    return value


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="kprof Spack compiler buildcache")
    parser.add_argument("--backend", choices=("docker", "native"), default="docker")
    parser.add_argument("--volume", help="Local persistent Docker volume")
    parser.add_argument("--image", help="Rocky container image")
    parser.add_argument("--cache-image", help="GHCR OCI buildcache image")
    subs = parser.add_subparsers(dest="action", required=True)
    for action in ("bootstrap", "system-install", "build", "restore", "push", "install", "inspect", "deps-build", "deps-install", "deps-restore", "deps-push"):
        command = subs.add_parser(action)
        if action in ("system-install", "build", "restore", "install", "push",
                      "deps-build", "deps-install", "deps-restore", "deps-push"):
            command.add_argument("--compiler", action="append", default=[])
    sync_cmd = subs.add_parser("sync")
    sync_cmd.add_argument("--check", action="store_true")
    get_cmd = subs.add_parser("get")
    get_cmd.add_argument("key")
    pin_cmd = subs.add_parser("set-packages-version")
    pin_cmd.add_argument("ref", help="Spack package repository tag, e.g. v2026.10.0")
    args = parser.parse_args(argv)
    status = 0
    prior_sigterm = None
    if os.environ.get("KPROF_HOST_UID"):
        def _terminate(signum: int, frame: object) -> None:
            raise InterruptedError("compiler operation interrupted by SIGTERM")
        prior_sigterm = signal.signal(signal.SIGTERM, _terminate)
    try:
        if args.action == "get":
            print(get(args.key))
        elif args.action == "set-packages-version":
            set_packages_version(args.ref)
        elif args.action == "sync":
            sync(check=args.check)
        else:
            execute(
                args.action, backend=args.backend, compilers=tuple(getattr(args, "compiler", ())),
                volume=args.volume, image=args.image, cache_image=args.cache_image,
            )
    except (ValueError, RuntimeError, subprocess.CalledProcessError, OSError) as exc:
        print(f"kprof compiler: {exc}", file=sys.stderr)
        status = 1
    except KeyboardInterrupt:
        status = 130
    finally:
        if prior_sigterm is not None:
            signal.signal(signal.SIGTERM, prior_sigterm)
        try:
            restore_workspace_ownership()
        except (ValueError, RuntimeError, subprocess.CalledProcessError, OSError) as exc:
            print(f"kprof compiler: ownership cleanup failed: {exc}", file=sys.stderr)
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
